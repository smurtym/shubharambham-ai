// migrate-data.js — Convert legacy city data from data.js to the new cities.csv format.
//
// Usage:
//   node migrate-data.js
//
// Output:
//   Prints CSV rows to stdout. Redirect to a file to capture:
//     node migrate-data.js >> ../../data/cities.csv
//
// Each output row has the format:
//   city_id,canonical_name,timezone,lang,city_name,region1,region2,region1_order,region2_order
//
// Where city_id is the zoom-15 Web Mercator quadkey encoded as a decimal u32.
// The quadkey is derived from the lat/lon decoded from the legacy city_id via helper.js.
//
// Prerequisites:
//   - Node.js >= 18 (ESM import support)
//   - Run from the data/migrate/ directory

import { decode_city_id } from './helper.js';
import { cities, categories } from './data.js';

// ---------------------------------------------------------------------------
// latlonToQuadkeyDecimal — encode (lat, lng) as a zoom-15 quadkey decimal u32
//
// Zoom-15: 2^15 = 32768 tiles per axis (Web Mercator).
// Each base-4 digit of the quadkey encodes one zoom level:
//   low bit  → tile_x bit
//   high bit → tile_y bit
// The 15 digits are assembled into a single decimal integer (same scheme as
// decode_city_id in astro-wasm/src/data/mod.rs).
// ---------------------------------------------------------------------------
function latlonToQuadkeyDecimal(lat, lng) {
    const ZOOM  = 15;
    const TILES = Math.pow(2, ZOOM); // 32768

    // Web Mercator tile coordinates at zoom 15
    const tile_x = Math.floor((lng + 180.0) / 360.0 * TILES);
    const sinLat  = Math.sin(lat * Math.PI / 180.0);
    const tile_y  = Math.floor(
        (0.5 - Math.log((1 + sinLat) / (1 - sinLat)) / (4 * Math.PI)) * TILES
    );

    // Clamp to valid tile range
    const tx = Math.max(0, Math.min(TILES - 1, tile_x));
    const ty = Math.max(0, Math.min(TILES - 1, tile_y));

    // Interleave bits into base-4 quadkey digits, then sum as decimal integer
    // digit[k] = (tx_bit_k) | (ty_bit_k << 1), accumulated as decimal: result += digit * 4^k
    let result = 0;
    for (let k = 0; k < ZOOM; k++) {
        const x_bit = (tx >> k) & 1;
        const y_bit = (ty >> k) & 1;
        const digit = x_bit | (y_bit << 1);
        result += digit * Math.pow(4, k);
    }

    return Math.round(result);
}

// ---------------------------------------------------------------------------
// decodeLegacyCityId — decode a legacy city_id (BigInt string from data.js)
// into { lat, lon, tz } using helper.js
// ---------------------------------------------------------------------------
function decodeLegacyCityId(cityIdStr) {
    return decode_city_id(BigInt(cityIdStr));
}

// ---------------------------------------------------------------------------
// convertCities — main conversion logic
//
// Returns an array of CSV row objects in the new cities.csv format.
// region1 and region2 are set from the category name (Telugu).
// region1_order = category_id, region2_order = 1 (all legacy data is India/Telugu).
// canonical_name is left blank — fill in manually or extend this script.
// ---------------------------------------------------------------------------
function convertCities() {
    const rows = [];

    for (const [legacyId, cityData] of Object.entries(cities)) {
        const { lat, lon, tz } = decodeLegacyCityId(legacyId);
        const cityIdDecimal     = latlonToQuadkeyDecimal(lat, lon);
        const categoryId        = cityData.category_id;
        const categoryName      = categories[String(categoryId)] ?? '';
        const cityName          = cityData.city_name;

        rows.push({
            city_id:        cityIdDecimal,
            // canonical_name: fill in with the English city name manually,
            // or extend this script to include an English name mapping in data.js
            canonical_name: '',
            timezone:       tz,
            lang:           'te',
            city_name:      cityName,
            region1:        categoryName,
            region2:        'భారతదేశం',
            region1_order:  categoryId,
            region2_order:  1,
        });
    }

    return rows;
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------
function main() {
    const rows = convertCities();

    // Print header comment so the output can be pasted directly into cities.csv
    console.log('# Auto-generated by migrate-data.js from data/migrate/data.js');
    console.log('# Review canonical_name column — it is empty and must be filled in.');
    console.log('# city_id,canonical_name,timezone,lang,city_name,region1,region2,region1_order,region2_order');

    for (const row of rows) {
        const line = [
            row.city_id,
            row.canonical_name,
            row.timezone,
            row.lang,
            row.city_name,
            row.region1,
            row.region2,
            row.region1_order,
            row.region2_order,
        ].join(',');
        console.log(line);
    }

    process.stderr.write(`\nConverted ${rows.length} cities.\n`);
}

main();
